export function getElectronShells(electrons) {
  const caps = [2, 8, 18, 32, 32, 18, 8];
  const res = [];
  let left = Math.max(0, electrons);
  for (let i = 0; i < caps.length && left > 0; i++) {
    const take = Math.min(left, caps[i]);
    res.push(take);
    left -= take;
  }
  return res;
}
